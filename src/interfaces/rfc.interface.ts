/**
 * Represents an RFC 7807 / RFC 9457 Problem Details object for HTTP APIs.
 *
 * @interface IRfcProblemDetails
 * @see https://datatracker.ietf.org/doc/html/rfc7807
 * @see https://datatracker.ietf.org/doc/html/rfc9457
 */
export interface IRfcProblemDetails {
    /**
     * A URI reference that identifies the problem type.
     * When dereferenced, it should provide human-readable documentation for the problem type.
     *
     * @type {string}
     */
    type: string;

    /**
     * A short, human-readable summary of the problem type.
     * It SHOULD NOT change from occurrence to occurrence of the problem.
     *
     * @type {string}
     */
    title: string;

    /**
     * The HTTP status code generated by the origin server for this occurrence of the problem.
     *
     * @type {number}
     */
    status: number;

    /**
     * A human-readable explanation specific to this occurrence of the problem.
     *
     * @type {string} [detail]
     */
    detail?: string;

    /**
     * A URI reference that identifies the specific occurrence of the problem.
     *
     * @type {string} [instance]
     */
    instance?: string;

    /**
     * Validation errors or invalid parameters associated with the problem occurrence.
     *
     * @type {unknown} [invalidParams]
     */
    invalidParams?: unknown;

    /**
     * Allows for additional extension members as permitted by RFC 7807 / RFC 9457.
     *
     * @type {unknown}
     */
    [key: string]: unknown;
}

/**
 * Alias for IRfcProblemDetails.
 */
export type IProblemDetails = IRfcProblemDetails;

